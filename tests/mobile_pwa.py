"""Mobile redesign checks. Run against preview: APP_URL=http://localhost:4173/Dare-me/ python3 tests/mobile_pwa.py."""
import os, shutil
from playwright.sync_api import sync_playwright, expect

with sync_playwright() as p:
    browser = p.chromium.launch(executable_path=shutil.which('chromium'), args=['--no-sandbox'])
    context = browser.new_context(viewport={'width':390,'height':844}, is_mobile=True, has_touch=True)
    page = context.new_page()
    errors=[]
    page.on('pageerror', lambda e:errors.append(str(e)))
    page.goto(os.environ.get('APP_URL','http://localhost:4173/Dare-me/'),wait_until='networkidle')
    nav=page.get_by_role('navigation',name='Main navigation')
    expect(page.get_by_role('heading',name='Today’s dares')).to_be_visible()
    expect(nav.get_by_role('button')).to_have_count(4)
    for width in [320,390,430,1024]:
        page.set_viewport_size({'width':width,'height':844})
        assert page.evaluate('document.documentElement.scrollWidth <= innerWidth'),f'overflow at {width}'
    page.set_viewport_size({'width':390,'height':844})
    page.get_by_role('button',name='Try this dare').first.click()
    dialog=page.get_by_role('dialog')
    expect(dialog.get_by_role('button',name='Accept dare')).to_be_disabled()
    dialog.get_by_role('checkbox').check()
    dialog.get_by_role('button',name='Accept dare').click()
    dialog.get_by_role('button',name='Open sample chat').click()
    expect(page.get_by_role('heading',name='Chats',exact=True)).to_be_visible()
    page.get_by_role('textbox',name='Message',exact=True).fill('Hello from the mobile redesign')
    page.get_by_role('button',name='Send message',exact=True).click()
    expect(page.get_by_text('Hello from the mobile redesign',exact=True)).to_be_visible()
    page.get_by_role('button',name='Back to chats',exact=True).click()
    expect(page.locator('.chat-sidebar')).to_be_visible()
    expect(page.locator('.chat-conversation')).to_have_count(0)
    page.reload(wait_until='networkidle')
    expect(page.get_by_role('heading',name='Chats',exact=True)).to_be_visible()
    nav.get_by_role('button',name='Feed',exact=True).click()
    expect(page.locator('.post-card').first).to_be_visible()
    page.get_by_role('tab',name='Following',exact=True).click()
    expect(page.get_by_role('heading',name='Your feed starts with a follow')).to_be_visible()
    page.get_by_role('button',name='Find people',exact=True).last.click()
    expect(page.get_by_role('dialog')).to_be_visible()
    page.get_by_role('button',name='Close dialog',exact=True).click()
    page.get_by_role('tab',name='For you',exact=True).click()
    post=page.locator('.post-card').first
    post.get_by_role('button',name='Like post',exact=True).click()
    expect(post.get_by_role('button',name='Unlike post',exact=True)).to_be_visible()
    post.get_by_role('button',name='Save post',exact=True).click()
    page.get_by_role('tab',name='Saved',exact=True).click()
    expect(page.locator('.post-card')).to_have_count(1)
    nav.get_by_role('button',name='Profile',exact=True).click()
    page.get_by_role('button',name='Get the app',exact=True).click()
    dialog=page.get_by_role('dialog')
    expect(dialog.get_by_role('heading',name='Dareme, one tap away')).to_be_visible()
    dialog.get_by_role('button',name='Keep exploring',exact=True).click()
    page.get_by_role('button',name='Preferences',exact=True).click()
    expect(page.get_by_role('switch',name='Private account',exact=True)).to_be_visible()
    page.go_back()
    expect(page.get_by_role('heading',name='Profile',exact=True)).to_be_visible()
    page.go_forward()
    expect(page.get_by_role('heading',name='Settings',exact=True)).to_be_visible()
    page.get_by_role('button',name='Done',exact=True).click()
    page.get_by_role('button',name='Share a moment',exact=True).last.click()
    dialog=page.get_by_role('dialog')
    dialog.get_by_role('textbox',name='Your post',exact=True).fill('A simpler day.')
    dialog.get_by_role('button',name='Share post',exact=True).click()
    expect(page.get_by_text('A simpler day.',exact=False)).to_be_visible()
    nav.get_by_role('button',name='Dares',exact=True).click()
    page.screenshot(path='/tmp/dareme-mobile.png',full_page=True)
    page.evaluate('navigator.serviceWorker.ready')
    cached = page.evaluate('async () => (await Promise.all((await caches.keys()).map(async key => (await (await caches.open(key)).keys()).map(r => r.url)))).flat()')
    assert not any('/api/' in url or '/uploads/' in url for url in cached), cached
    assert any('/assets/' in url and '.js' in url for url in cached), 'Build scripts were not precached'
    page.reload(wait_until='networkidle')
    assert page.evaluate('!!navigator.serviceWorker.controller')
    manifest=page.evaluate("async () => await (await fetch(document.querySelector('link[rel=manifest]').href)).json()")
    assert manifest['display']=='standalone'
    for icon in manifest['icons']:
        assert page.evaluate('(src) => fetch(new URL(src, document.querySelector("link[rel=manifest]").href)).then(r=>r.ok)',icon['src'])
    context.set_offline(True)
    page.reload(wait_until='networkidle')
    expect(page.get_by_role('heading',name='Today’s dares')).to_be_visible()
    context.set_offline(False)
    assert not errors,errors
    page.emulate_media(reduced_motion='reduce')
    assert page.locator('.dare-button').first.evaluate('(e)=>getComputedStyle(e).transitionDuration').split(',')[0]=='1e-05s'
    print('PASS: four tabs, 320–1024px layout, mutual consent, chat, likes, saves, profile, post creation, chat list, browser back, install dialog, PWA icons, precached build, offline demo, reduced motion')
    browser.close()
